def _chunked(data: bytes) -> str:
    h = data.hex()
    chunks = [h[i:i + 120] for i in range(0, len(h), 120)] or [""]
    return "\n    ".join(f'"{c}"' for c in chunks)


def hexlist(name: str, items: list[bytes]) -> None:
    assert items, name  # C++には長さ0の配列がない
    out.append(f"inline constexpr const char* {name}[] = {{")
    out.extend(f"    {_chunked(it)}," for it in items)
    out.append("};")


def intlist(name: str, items: list[int]) -> None:
    assert items, name
    out.append(f"inline constexpr long long {name}[] = {{{', '.join(str(int(v)) for v in items)}}};")


