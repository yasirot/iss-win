def hexconst(name: str, data: bytes) -> None:
    # MSVCは1つの文字列リテラルを約16 KBまでに制限するので、長いリテラルは分割する。
    h = data.hex()
    chunks = [h[i:i + 120] for i in range(0, len(h), 120)] or [""]
    body = "\n    ".join(f'"{c}"' for c in chunks)
    out.append(f"inline constexpr const char* {name} =\n    {body};")


def intconst(name: str, v: int) -> None:
    out.append(f"inline constexpr long long {name} = {v};")


