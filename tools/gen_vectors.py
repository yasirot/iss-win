def ue(v: int) -> str:
    v += 1
    return "0" * (v.bit_length() - 1) + format(v, "b")


def escape_epb(rbsp: bytes) -> bytes:
    res, zeros = bytearray(), 0
    for b in rbsp:
        if zeros >= 2 and b <= 3:
            res.append(3)
            zeros = 0
        res.append(b)
        zeros = zeros + 1 if b == 0 else 0
    return bytes(res)


def slice_nal(t: int, first_mb: int, slice_type: int) -> bytes:
    bits = ue(first_mb) + ue(slice_type) + ue(0) + "1"
    bits += "0" * (-len(bits) % 8)
    return avc_hdr(t, 2) + escape_epb(int(bits, 2).to_bytes(len(bits) // 8, "big") + sbytes(12))


