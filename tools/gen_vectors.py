def srtp_protect(hdr: bytes, payload: bytes, roc: int) -> bytes:
    ck = srtp_mod._srtp_kdf(_mk, _ms, 0, 32)
    ak = srtp_mod._srtp_kdf(_mk, _ms, 1, 20)
    salt = srtp_mod._srtp_kdf(_mk, _ms, 2, 14)
    seq = struct.unpack(">H", hdr[2:4])[0]
    ssrc = struct.unpack(">I", hdr[8:12])[0]
    iv = (int.from_bytes(salt + b"\0\0", "big") ^ (ssrc << 64) ^ (((roc << 16) | seq) << 16)).to_bytes(16, "big")
    body = hdr + Cipher(algorithms.AES(ck), modes.CTR(iv)).encryptor().update(payload)
    return body + _hmac.new(ak, body + roc.to_bytes(4, "big"), "sha1").digest()[:10]


